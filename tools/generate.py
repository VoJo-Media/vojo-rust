#!/usr/bin/env python3
"""Generate src/generated/ from the shared API files. Standard library only, plus rustfmt.

    python3 tools/generate.py          write the generated code
    python3 tools/generate.py --check  fail if the generated code is stale
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = next(p for p in (ROOT / "shared", ROOT.parent / "shared") if p.exists()) / "api"
OUT = ROOT / "src" / "generated"
HEADER = "// Code generated by tools/generate.py from the shared API files. DO NOT EDIT.\n\n"
SCALARS = {"string": "String", "integer": "i64", "number": "f64", "boolean": "bool"}
KEYWORDS = {
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct",
    "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "gen",
    "macro", "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
}
# Names that would shadow the prelude inside the generated modules.
RESERVED = {"Option", "Result", "String", "Vec", "Box", "Self", "Default"}
VALUE = "serde_json::Value"
MAP = "serde_json::Map<String, serde_json::Value>"


def words(name: str) -> list[str]:
    spaced = re.sub(r"(?<=[a-z0-9])([A-Z])", r" \1", name)
    return [w for w in re.split(r"[^A-Za-z0-9]+|\s+", spaced) if w]


def camel(name: str) -> str:
    text = "".join(w[:1].upper() + w[1:] for w in words(name))
    return "V" + text if text[:1].isdigit() else text


def snake(name: str) -> str:
    return "_".join(w.lower() for w in words(name))


def ident(name: str) -> str:
    text = snake(name)
    if text[:1].isdigit():
        text = "n" + text
    return f"r#{text}" if text in KEYWORDS else text


def type_name(name: str) -> str:
    text = camel(name)
    return text + "Object" if text in RESERVED else text


def doc(text: str | None, indent: str = "") -> str:
    """Rustdoc lines. Markdown in descriptions is escaped, so nothing becomes a link, tag or doctest."""
    out = []
    for paragraph in re.split(r"\n\s*\n", text or ""):
        paragraph = re.sub(r"\s+", " ", paragraph).strip()
        if not paragraph:
            continue
        parts = paragraph.split("`")
        for i in range(0, len(parts), 2):
            parts[i] = re.sub(r"([\[\]<>\\])", r"\\\1", parts[i])
            parts[i] = re.sub(r"(https?://[^\s)\\]+)", r"<\1>", parts[i])
        paragraph = "`".join(parts) if len(parts) % 2 else paragraph.replace("`", "'")
        if paragraph[:1] in "#>-+=*|":
            paragraph = "\\" + paragraph
        out.append(f"{indent}/// {paragraph}\n")
    return f"{indent}///\n".join(out)


class Types:
    """One struct per object schema and one enum per named enum, in response or body mode."""

    def __init__(self, schemas: dict) -> None:
        self.schemas = schemas
        self.mode: dict[str, str] = {}
        self.out: dict[str, str] = {}
        # Schemas any response reaches. A request body using one gets its own Input
        # type, because bodies distinguish a field left out from one sent as null.
        self.in_responses: set[str] = set()

    def reach(self, schema: object) -> None:
        if isinstance(schema, dict):
            if "$ref" in schema:
                name = schema["$ref"].rsplit("/", 1)[-1]
                if name not in self.in_responses:
                    self.in_responses.add(name)
                    self.reach(self.schemas[name])
            for value in schema.values():
                self.reach(value)
        elif isinstance(schema, list):
            for value in schema:
                self.reach(value)

    def named(self, name: str, mode: str) -> str:
        text = type_name(name)
        return text + "Input" if mode == "body" and name in self.in_responses else text

    def resolve(self, schema: dict) -> dict:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[-1]]
        return schema

    def unwrap(self, schema: dict) -> tuple[dict, bool]:
        nullable = False
        options = schema.get("oneOf") or schema.get("anyOf")
        if options:
            real = [o for o in options if o.get("type") != "null"]
            nullable = len(real) != len(options)
            schema = real[0] if len(real) == 1 else {}
        if len(schema.get("allOf", [])) == 1:
            schema = schema["allOf"][0]
        kind = schema.get("type")
        if isinstance(kind, list):
            nullable = nullable or "null" in kind
            real_kinds = [k for k in kind if k != "null"]
            schema = {**schema, "type": real_kinds[0] if len(real_kinds) == 1 else None}
        return schema, nullable

    def rust_type(self, schema: dict, context: str, mode: str) -> tuple[str, bool]:
        """(Rust type without Option, whether null is allowed)."""
        schema, nullable = self.unwrap(schema)
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            inner, inner_nullable = self.unwrap(self.resolve(schema))
            if inner.get("type") == "object" and inner.get("properties"):
                self.emit_struct(self.named(name, mode), inner, mode)
                return self.named(name, mode), nullable or inner_nullable
            if inner.get("enum"):
                self.emit_enum(type_name(name), inner)
                return type_name(name), nullable or inner_nullable
            text, more = self.rust_type(inner, context, mode)
            return text, nullable or more or inner_nullable
        kind = schema.get("type")
        if kind == "array":
            inner, _ = self.rust_type(schema.get("items", {}), context + "Item", mode)
            return f"Vec<{inner}>", nullable
        if kind == "object":
            if schema.get("properties"):
                self.emit_struct(context, schema, mode)
                return context, nullable
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                inner, _ = self.rust_type(extra, context + "Value", mode)
                return f"std::collections::BTreeMap<String, {inner}>", nullable
            return MAP, nullable
        return SCALARS.get(kind, VALUE), nullable

    def field(self, wire: str, schema: dict, owner: str, required: bool, mode: str) -> str:
        text, nullable = self.rust_type(schema, owner + camel(wire), mode)
        if text == owner:
            text = f"Box<{text}>"
        attrs = []
        if mode == "response" and required and not nullable:
            kind = text
            attrs.append('default, deserialize_with = "crate::util::null_default"')
        elif mode == "response":
            kind = f"Option<{text}>"
            attrs.append('default, skip_serializing_if = "Option::is_none"')
        elif required:
            # Always sent; a nullable one is sent as null when None.
            kind = f"Option<{text}>" if nullable else text
            attrs.append("default")
        else:
            # Left out is different from sent as null.
            kind = f"Option<Option<{text}>>" if nullable else f"Option<{text}>"
            attrs.append('default, skip_serializing_if = "Option::is_none"')
        name = ident(wire)
        if name.removeprefix("r#") != wire:
            attrs.insert(0, f'rename = "{wire}"')
        notes = schema.get("description") or ""
        enum = self.unwrap(self.resolve(self.unwrap(schema)[0]))[0].get("enum")
        if enum and "$ref" not in self.unwrap(schema)[0]:
            values = ", ".join(f"`{v}`" for v in enum if v is not None)
            notes = f"{notes} One of {values}. New values may appear.".strip()
        return doc(notes, "    ") + f"    #[serde({', '.join(attrs)})]\n    pub {name}: {kind},\n"

    def emit_struct(self, name: str, schema: dict, mode: str) -> None:
        if name in self.mode:
            if self.mode[name] != mode:
                raise SystemExit(f"{name} is both a response and a request body; the generator needs a second name")
            return
        self.mode[name] = mode
        required = set(schema.get("required", []))
        fields = "".join(self.field(k, v, name, k in required, mode) for k, v in schema.get("properties", {}).items())
        # Responses can gain fields, so callers may not build them field by field.
        lock = "#[non_exhaustive]\n" if mode == "response" else ""
        self.out[name] = (
            (doc(schema.get("description")) or f"/// A `{name}`.\n")
            + "#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]\n"
            + f"{lock}pub struct {name} {{\n{fields}}}\n"
        )

    def emit_enum(self, name: str, schema: dict) -> None:
        if name in self.mode:
            return
        self.mode[name] = "enum"
        seen: set[str] = set()
        variants = []
        for value in schema["enum"]:
            if not isinstance(value, str):
                continue
            variant = camel(value) or "Empty"
            while variant in seen or variant == "Unknown":
                variant += "Value"
            seen.add(variant)
            variants.append(f"        /// `{value}`\n        {variant} = \"{value}\",\n")
        notes = doc(schema.get("description"), "    ") or f"    /// A `{name}` value. New values may appear.\n"
        self.out[name] = f"string_enum! {{\n{notes}    {name} {{\n{''.join(variants)}    }}\n}}\n"

    def render(self) -> str:
        body = "\n".join(self.out[n] for n in sorted(self.out))
        uses = "use crate::util::string_enum;\n\n" if "string_enum!" in body else ""
        return uses + body


class Resources:
    def __init__(self, contract: dict, operations: list[dict], types: Types) -> None:
        self.contract = contract
        self.operations = operations
        self.types = types
        self.params: list[str] = []
        self.tests: list[str] = []

    def parameter(self, op: dict, name: str) -> dict:
        item = self.contract["paths"][op["path"]]
        for parameter in item[op["http_method"].lower()].get("parameters", []) + item.get("parameters", []):
            if "$ref" in parameter:
                parameter = self.contract["components"]["parameters"][parameter["$ref"].rsplit("/", 1)[-1]]
            if parameter["name"] == name:
                return parameter
        raise KeyError(name)

    def params_struct(self, op: dict, name: str) -> str:
        fields, setters, query = [], [], []
        for q in op["query_params"]:
            wire = q["name"]
            parameter = self.parameter(op, wire)
            raw = parameter.get("schema", {})
            schema, _ = self.types.unwrap(raw)
            field = ident(wire)
            notes = parameter.get("description") or ""
            if "$ref" in schema:
                enum = type_name(schema["$ref"].rsplit("/", 1)[-1])
                self.types.emit_enum(enum, self.types.resolve(schema))
                kind, arg, value, text = f"models::{enum}", f"impl Into<models::{enum}>", "value.into()", "v.as_str().to_owned()"
            else:
                values = schema.get("enum")
                if values:
                    notes = f"{notes} One of {', '.join(f'`{v}`' for v in values if v is not None)}.".strip()
                kind = SCALARS.get(schema.get("type"), "String")
                if kind == "String":
                    arg, value, text = "impl Into<String>", "value.into()", "v.clone()"
                else:
                    arg, value, text = kind, "value", "v.to_string()"
            fields.append(doc(notes, "    ") + f"    pub {field}: Option<{kind}>,\n")
            setters.append(
                (doc(notes, "    ") or f"    /// Sets `{wire}`.\n")
                + f"    pub fn {field}(mut self, value: {arg}) -> Self {{\n        self.{field} = Some({value});\n        self\n    }}\n"
            )
            query.append(f'        if let Some(v) = &self.{field} {{\n            query.push(("{wire}", {text}));\n        }}\n')
        self.params.append(
            f"/// The query for `{'.'.join(op['resource'])}.{op['method']}`. Every field is optional.\n"
            f"#[derive(Clone, Debug, Default, PartialEq)]\npub struct {name} {{\n{''.join(fields)}}}\n\n"
            f"impl {name} {{\n    /// An empty query.\n    pub fn new() -> Self {{\n        Self::default()\n    }}\n\n"
            + "\n".join(setters)
            + "\n    pub(crate) fn to_query(&self) -> Vec<(&'static str, String)> {\n"
            f"        let mut query = Vec::new();\n{''.join(query)}        query\n    }}\n}}\n"
        )
        return name

    def body_type(self, op: dict, prefix: str) -> tuple[str, bool] | None:
        body = self.contract["paths"][op["path"]][op["http_method"].lower()].get("requestBody")
        if not body:
            return None
        schema = body["content"]["application/json"]["schema"]
        name = self.types.named(schema["$ref"].rsplit("/", 1)[-1], "body") if "$ref" in schema else prefix + "Request"
        self.types.emit_struct(name, self.types.resolve(schema), "body")
        return name, bool(body.get("required"))

    def method(self, op: dict, prefix: str) -> tuple[str, str]:
        name = ident(op["method"])
        response = op["response"]
        returns = response["returns"]
        model = response.get("data_schema") or response.get("item_schema")
        rust_model = None
        if model:
            rust_model = type_name(model)
            self.types.emit_struct(rust_model, self.types.schemas[model], "response")
            rust_model = f"models::{rust_model}"
        ids = [ident(p) for p in op["path_params"]]
        args = [f"{i}: &str" for i in ids]
        call_args = [f'"id_{p}"' for p in op["path_params"]]
        query = None
        if op["query_params"]:
            query = self.params_struct(op, prefix + camel(op["method"]) + "Params")
            args.append(f"params: params::{query}")
            call_args.append("Default::default()")
        body = self.body_type(op, prefix + camel(op["method"]))
        if body:
            body_name, required = body
            args.append(f"body: &models::{body_name}" if required else f"body: Option<&models::{body_name}>")
            call_args.append("&Default::default()" if required else "None")

        # Everything is prepared before the future, which owns what it needs and so
        # can be stored or spawned. Errors from preparing surface when it is awaited.
        lines = []
        page = returns == "page"
        if ids:
            pairs = ", ".join(f'("{p}", {i})' for p, i in zip(op["path_params"], ids))
            expand = f'crate::util::expand_path("{op["path"]}", &[{pairs}])'
            if page:
                lines.append(f"        let path = match {expand} {{\n            Ok(path) => path,\n            Err(e) => return crate::List::failed(e),\n        }};\n")
            else:
                lines.append(f"        let path = {expand};\n")
            path = "path" if page else "path: path?"
        else:
            path = f'path: "{op["path"]}".to_owned()'
        if body and body[1]:
            lines.append("        let body = crate::util::to_json(body).map(Some);\n")
        elif body:
            lines.append("        let body = body.map(crate::util::to_json).transpose();\n")
        if query and not page:
            lines.append("        let query = params.to_query();\n")
        request = (
            f"Request {{ method: \"{op['http_method']}\", {path}, "
            f"{('query: params.to_query()' if page else 'query') if query else 'query: Vec::new()'}, "
            f"{'body: body?' if body else 'body: None'}, "
            f"retry_safe: {str(op['retry_safe']).lower()}, keyed: {str(op['idempotency_key']).lower()}, "
            f"early_access: {str(op['available_in_early_access']).lower()} }}"
        )

        if page:
            result = f"crate::List<{rust_model}>"
            start = "params.cursor.clone()" if query else "None"
            lines.append(f"        crate::List::new(self.client.clone(), {request}, {start})\n")
            signature = f"pub fn {name}(&self, {', '.join(args)}) -> {result}"
        else:
            if returns == "void":
                result, call = "crate::Result<()>", "void"
            else:
                inner = f"Vec<{rust_model}>" if response.get("is_array") else rust_model
                result, call = f"crate::Result<crate::Response<{inner}>>", "data"
            lines.append(f"        let client = self.client.clone();\n        async move {{ client.{call}({request}).await }}\n")
            signature = f"pub fn {name}(&self, {', '.join(args)}) -> impl Future<Output = {result}> + Send + 'static"

        notes = op.get("summary") or ""
        if not op["available_in_early_access"]:
            notes += "\n\nNot yet available during early access: the API may answer with a 404."
        if op["idempotency_key"]:
            notes += "\n\nSafe to retry: every attempt carries one `Idempotency-Key`, generated unless you set `RequestOptions::idempotency_key`."
        code = "\n" + doc(notes, "    ") + f"    {signature.replace('(&self, )', '(&self)')} {{\n{''.join(lines)}    }}\n"

        blocking_args = ", ".join(a.split(":")[0] for a in args)
        if returns == "page":
            blocking = f"    pub fn {name}(&self, {', '.join(args)}) -> List<{rust_model}> {{\n        List::new(self.inner.{name}({blocking_args}), self.runtime.clone())\n    }}\n"
        else:
            blocking = f"    pub fn {name}(&self, {', '.join(args)}) -> {result} {{\n        self.runtime.block_on(self.inner.{name}({blocking_args}))\n    }}\n"
        blocking = "\n" + doc(notes, "    ") + blocking.replace("(&self, )", "(&self)")

        self.test(op, call_args, returns, bool(response.get("is_array")))
        return code, blocking

    def test(self, op: dict, call_args: list[str], returns: str, is_array: bool) -> None:
        chain = "".join(f".{ident(p)}()" for p in op["resource"])
        call = f"client{chain}.{ident(op['method'])}({', '.join(call_args)})"
        call = f"{call}.first_page().await.map(|_| ())" if returns == "page" else f"{call}.await.map(|_| ())"
        success = {
            "page": '(200, r#"{"data":[],"meta":{"has_more":false}}"#)',
            "void": '(204, "")',
        }.get(returns, '(200, r#"{"data":[],"meta":{}}"#)' if is_array else '(200, r#"{"data":{},"meta":{}}"#)')
        path = op["path"]
        for p in op["path_params"]:
            path = path.replace("{" + p + "}", f"id_{p}")
        attempts = 2 if op["retry_safe"] else 1
        hint = "true" if not op["available_in_early_access"] else "false"
        self.tests.append(
            f"""
#[tokio::test(start_paused = true)]
async fn {snake(op['operation_id'])}() {{
    let (client, stub) = stub_client(vec![{success}]);
    let result = {call};
    assert!(result.is_ok(), "{{result:?}}");
    let sent = stub.requests();
    assert_eq!(sent.len(), 1);
    assert_eq!(sent[0].method, "{op['http_method']}");
    assert_eq!(path_of(&sent[0].url), "{path}");
    assert!(sent[0].headers.get("Idempotency-Key").{'is_some' if op['idempotency_key'] else 'is_none'}());

    let (client, stub) = stub_client(vec![(503, ""), {success}]);
    let _ = {call};
    assert_eq!(stub.requests().len(), {attempts}, "retry_safe is {str(op['retry_safe']).lower()}");

    let (client, _) = stub_client(vec![(404, r#"{{"title":"Not found","code":"not_found"}}"#)]);
    let error = {call}.unwrap_err();
    assert!({'' if hint == 'true' else '!'}error.to_string().contains("early access"), "{{error}}");
}}
"""
        )

    def tree(self) -> dict:
        root: dict = {"children": {}, "operations": []}
        for op in self.operations:
            node = root
            for part in op["resource"]:
                node = node["children"].setdefault(part, {"children": {}, "operations": []})
            node["operations"].append(op)
        return root

    def structs(self, node: dict, chain: list[str]) -> tuple[list[str], list[str]]:
        code: list[str] = []
        blocking: list[str] = []
        for name, child in node["children"].items():
            more, more_blocking = self.structs(child, [*chain, name])
            code += more
            blocking += more_blocking
        kids = [(ident(n), "".join(camel(p) for p in [*chain, n]), ".".join([*chain, n])) for n in node["children"]]
        accessors = "".join(
            f"\n    /// The `{path}` resource.\n    pub fn {a}(&self) -> {k} {{\n        {k} {{ client: self.{'clone()' if not chain else 'client.clone()'} }}\n    }}\n"
            for a, k, path in kids
        )
        blocking_accessors = "".join(
            f"\n    /// The `{path}` resource.\n    pub fn {a}(&self) -> {k} {{\n        {k} {{ inner: self.inner.{a}(), runtime: self.runtime.clone() }}\n    }}\n"
            for a, k, path in kids
        )
        if not chain:
            code.append(f"impl crate::Client {{{accessors}}}\n")
            blocking.append(f"impl Client {{{blocking_accessors}}}\n")
            return code, blocking
        struct = "".join(camel(p) for p in chain)
        methods, blocking_methods = [], []
        for op in node["operations"]:
            m, b = self.method(op, struct)
            methods.append(m)
            blocking_methods.append(b)
        path = ".".join(chain)
        code.append(
            f"/// The `{path}` resource.\n#[derive(Clone, Debug)]\npub struct {struct} {{\n    client: crate::Client,\n}}\n\n"
            f"impl {struct} {{{accessors}{''.join(methods)}}}\n"
        )
        blocking.append(
            f"/// The `{path}` resource.\n#[derive(Clone, Debug)]\npub struct {struct} {{\n"
            f"    inner: crate::resources::{struct},\n    runtime: Arc<Runtime>,\n}}\n\n"
            f"impl {struct} {{{blocking_accessors}{''.join(blocking_methods)}}}\n"
        )
        return code, blocking

    def render(self) -> dict[str, str]:
        code, blocking = self.structs(self.tree(), [])
        tests = "".join(self.tests)
        return {
            "resources.rs": "use std::future::Future;\n\nuse super::{models, params};\nuse crate::client::Request;\n\n" + "\n".join(code),
            "blocking.rs": (
                "use std::sync::Arc;\n\nuse tokio::runtime::Runtime;\n\nuse super::{models, params};\n"
                "use crate::blocking::{Client, List};\n\n" + "\n".join(blocking)
            ),
            "params.rs": "use super::models;\n\n" + "\n".join(self.params),
            "operations_test.rs": (
                "//! Every operation, called by the names in the manifest against a stub.\n\n"
                "use crate::test_support::{path_of, stub_client};\n" + tests
            ),
        }


def rustfmt(text: str) -> str:
    result = subprocess.run(
        ["rustfmt", "--edition", "2021", "--config-path", str(ROOT / "rustfmt.toml")],
        input=text, capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"rustfmt failed:\n{result.stderr}")
    return result.stdout


def build() -> dict[str, str]:
    contract = json.loads((SHARED / "vojo-api.public.json").read_text())
    webhooks = json.loads((SHARED / "vojo-webhooks.public.json").read_text())
    manifest = json.loads((SHARED / "operations.json").read_text())

    types = Types(contract["components"]["schemas"])
    for op in manifest["operations"]:
        model = op["response"].get("data_schema") or op["response"].get("item_schema")
        if model:
            types.reach({"$ref": f"#/components/schemas/{model}"})
    files = Resources(contract, manifest["operations"], types).render()
    files["models.rs"] = types.render()

    events = Types(webhooks["components"]["schemas"])
    constants = []
    for event in manifest["events"]:
        name = type_name(event["schema"])
        events.emit_struct(name, events.schemas[event["schema"]], "response")
        constants.append(
            f"    /// A `{event['type']}` event: {(event.get('summary') or '').rstrip('.')}. Decode it as [`super::events::{name}`].\n"
            f"    pub const {snake(event['type']).upper()}: &str = \"{event['type']}\";\n"
        )
    files["webhook_events.rs"] = (
        "/// The event payloads, to decode a verified [`Event`](crate::webhook::Event) into.\n"
        f"pub mod events {{\n{events.render()}}}\n\n"
        f"/// The event types this version knows. Others may arrive and verify normally.\npub mod event_type {{\n{''.join(constants)}}}\n"
    )
    files["mod.rs"] = (
        "pub(crate) mod webhook_events;\npub(crate) mod models;\npub(crate) mod params;\npub(crate) mod resources;\n\n"
        '#[cfg(feature = "blocking")]\npub(crate) mod blocking;\n\n#[cfg(test)]\nmod operations_test;\n\n'
        f"/// The `Vojo-Version` this release was built against. It is sent on every\n"
        f"/// request; change it with `ClientBuilder::version`.\npub const API_VERSION: &str = \"{manifest['api_version']}\";\n"
    )
    return {name: rustfmt(HEADER + text) for name, text in files.items()}


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        stale = [n for n, text in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
        stale += [p.name for p in OUT.glob("*.rs") if p.name not in files]
        if stale:
            print(f"Generated code is stale ({', '.join(sorted(stale))}). Run: python3 tools/generate.py", file=sys.stderr)
            return 1
        print("Generated code is up to date.")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path in OUT.glob("*.rs"):
        if path.name not in files:
            path.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"Wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
